MODULE MODE_TIWMX
  IMPLICIT NONE
CONTAINS
  REAL FUNCTION ESATW(TIWMX, TT)
    REAL, INTENT(IN) :: TIWMX
    REAL, INTENT(IN) :: TT

    ESATW = EXP(17.2694 * (TT - 273.16) / MAX(TT - 35.86, 1.0E-6))
  END FUNCTION ESATW

  REAL FUNCTION ESATI(TIWMX, TT)
    REAL, INTENT(IN) :: TIWMX
    REAL, INTENT(IN) :: TT

    IF (TT >= TIWMX) THEN
      ESATI = ESATW(TIWMX, TT)
    ELSE
      ESATI = EXP(21.8746 * (TT - 273.16) / MAX(TT - 7.66, 1.0E-6))
    END IF
  END FUNCTION ESATI
END MODULE MODE_TIWMX
