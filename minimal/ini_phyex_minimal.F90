MODULE MODI_INI_PHYEX
  USE MODD_IO, ONLY : TFILEDATA
  USE MODD_PHYEX, ONLY : PHYEX_t
  USE MODD_PHYEX_AERO, ONLY : PHYEX_AERO_t
  IMPLICIT NONE
CONTAINS
  SUBROUTINE INI_PHYEX(HPROGRAM, TPFILE, LDNEEDNAM, KLUOUT, KFROM, KTO, &
                     & PTSTEP, PDZMIN, &
                     & CMICRO, CSCONV, CTURB, &
                     & PHYAERO, &
                     & LDCHANGEMODEL, LDDEFAULTVAL, LDREADNAM, LDCHECK, &
                     & KPRINT, LDINIT, &
                     & PHYEX_IN, PHYEX_OUT)
    CHARACTER(LEN=6), INTENT(IN) :: HPROGRAM
    TYPE(TFILEDATA), INTENT(IN) :: TPFILE
    LOGICAL, INTENT(IN) :: LDNEEDNAM
    INTEGER, INTENT(IN) :: KLUOUT
    INTEGER, INTENT(IN) :: KFROM
    INTEGER, INTENT(IN) :: KTO
    REAL, INTENT(IN) :: PTSTEP
    REAL, INTENT(IN) :: PDZMIN
    CHARACTER(LEN=4), INTENT(IN) :: CMICRO
    CHARACTER(LEN=4), INTENT(IN) :: CSCONV
    CHARACTER(LEN=4), INTENT(IN) :: CTURB
    TYPE(PHYEX_AERO_t), OPTIONAL, INTENT(INOUT) :: PHYAERO
    LOGICAL, OPTIONAL, INTENT(IN) :: LDCHANGEMODEL
    LOGICAL, OPTIONAL, INTENT(IN) :: LDDEFAULTVAL
    LOGICAL, OPTIONAL, INTENT(IN) :: LDREADNAM
    LOGICAL, OPTIONAL, INTENT(IN) :: LDCHECK
    INTEGER, OPTIONAL, INTENT(IN) :: KPRINT
    LOGICAL, OPTIONAL, INTENT(IN) :: LDINIT
    TYPE(PHYEX_t), OPTIONAL, INTENT(IN) :: PHYEX_IN
    TYPE(PHYEX_t), OPTIONAL, INTENT(INOUT) :: PHYEX_OUT

    IF (PRESENT(PHYEX_OUT)) THEN
      IF (PRESENT(PHYEX_IN)) PHYEX_OUT = PHYEX_IN
      IF (PHYEX_OUT%MISC%CPROGRAM == '') PHYEX_OUT%MISC%CPROGRAM = HPROGRAM
      IF (PHYEX_OUT%PARAM_MFSHALLN%CMF_UPDRAFT == '') PHYEX_OUT%PARAM_MFSHALLN%CMF_UPDRAFT = CSCONV
      IF (PHYEX_OUT%PARAM_MFSHALLN%CMF_CLOUD == '') PHYEX_OUT%PARAM_MFSHALLN%CMF_CLOUD = 'NONE'
      IF (PHYEX_OUT%TURBN%CTURBDIM == '') PHYEX_OUT%TURBN%CTURBDIM = '1DIM'
    END IF

    IF (PRESENT(PHYAERO)) CONTINUE
    IF (PRESENT(LDCHANGEMODEL)) CONTINUE
    IF (PRESENT(LDDEFAULTVAL)) CONTINUE
    IF (PRESENT(LDREADNAM)) CONTINUE
    IF (PRESENT(LDCHECK)) CONTINUE
    IF (PRESENT(KPRINT)) CONTINUE
    IF (PRESENT(LDINIT)) CONTINUE
    IF (LEN(HPROGRAM) < 0) CONTINUE
    IF (TPFILE%NLU == -HUGE(0)) CONTINUE
    IF (LDNEEDNAM .AND. .FALSE.) CONTINUE
    IF (KLUOUT == -HUGE(0)) CONTINUE
    IF (KFROM == HUGE(0)) CONTINUE
    IF (KTO == HUGE(0)) CONTINUE
    IF (PTSTEP < -HUGE(PTSTEP)) CONTINUE
    IF (PDZMIN < -HUGE(PDZMIN)) CONTINUE
    IF (CMICRO == '----') CONTINUE
    IF (CSCONV == '----') CONTINUE
    IF (CTURB == '----') CONTINUE
  END SUBROUTINE INI_PHYEX
END MODULE MODI_INI_PHYEX
