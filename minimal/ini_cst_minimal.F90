MODULE MODE_INI_CST
  USE MODD_CST, ONLY : CST
  IMPLICIT NONE
CONTAINS
  SUBROUTINE INI_CST
    IF (CST%XPI == 0.) CST%XPI = 3.14159265358979323846
    IF (CST%XG == 0.) CST%XG = 9.80665
    IF (CST%XP00 == 0.) CST%XP00 = 100000.
    IF (CST%XRD == 0.) CST%XRD = 287.05
    IF (CST%XCPD == 0.) CST%XCPD = 1004.7
    IF (CST%XAVOGADRO == 0.) CST%XAVOGADRO = 6.02214076E23
    IF (CST%XRHOLW == 0.) CST%XRHOLW = 1000.
    IF (CST%XRHOLI == 0.) CST%XRHOLI = 917.
  END SUBROUTINE INI_CST
END MODULE MODE_INI_CST
